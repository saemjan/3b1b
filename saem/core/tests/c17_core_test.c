/* Seal and core tests.
 *  The seal: the C digest and tag must equal the ones computed by tools/seal.py (an independent implementation, included as generated
 *  text); every single byte and field of the sealed tables must change the digest.
 *  The core: it refuses to start on wrong tables or key and when it cannot write its first receipt; the gate verdicts; consecutive-reject
 *  quarantine that survives a restart and is lifted only by a journaled approval; freeze on any mutation, first reason wins, lifted only by
 *  a restart that re-verifies; the journal monitor; power cuts at every write; threads (run under -fsanitize=thread). */
