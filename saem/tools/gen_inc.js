// Writes the data tables the C++ core embeds, straight from the reference engine, so the two can never drift apart by a typo.
// Usage: node tools/gen_inc.js   (run from the project root)
const fs = require('fs'), path = require('path');
global.EF = require('../reference/src/ef.js'); global.CBT = require('../reference/src/cbt.js'); global.GEN = require('../reference/src/gen.js');
const out = path.join(__dirname, '..', 'core', 'src', 'data');
fs.mkdirSync(out, { recursive: true });
function raw(name, text, tag) {
  // a C++ raw string; long tables are split into chunks that the compiler joins again
  const parts = []; const N = 6000;
  for (let i = 0; i < text.length; i += N) parts.push(text.slice(i, i + N));
  const body = parts.map(p => 'R"' + tag + '(' + p + ')' + tag + '"').join('\n');
  fs.writeFileSync(path.join(out, name), '// generated by tools/gen_inc.js from the reference engine; do not edit\n' + body + '\n');
}
raw('vectors.inc', JSON.stringify(GEN.VECTORS), 'V');
raw('syllabus.inc', EF.PHYSICS_SYLLABUS, 'S');
raw('demo_text.inc', CBT.DEMO_TEXT, 'D');
console.log('wrote', fs.readdirSync(out).join(', '));
